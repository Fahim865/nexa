CREATE TABLE `users` (
  `id` int AUTO_INCREMENT NOT NULL,
  `openId` varchar(64) NOT NULL,
  `name` text,
  `email` varchar(320),
  `loginMethod` varchar(64),
  `role` enum('user','admin') NOT NULL DEFAULT 'user',
  `plan` enum('FREE','PREMIUM') NOT NULL DEFAULT 'FREE',
  `subscriptionStatus` enum('INACTIVE','ACTIVE','CANCELED','PAST_DUE','TRIALING') NOT NULL DEFAULT 'INACTIVE',
  `subscriptionStartDate` timestamp NULL,
  `subscriptionEndDate` timestamp NULL,
  `paymentProvider` varchar(64),
  `providerCustomerId` varchar(255),
  `providerSubscriptionId` varchar(255),
  `createdAt` timestamp NOT NULL DEFAULT (now()),
  `updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
  `lastSignedIn` timestamp NOT NULL DEFAULT (now()),
  CONSTRAINT `users_id` PRIMARY KEY(`id`),
  CONSTRAINT `users_openId_unique` UNIQUE(`openId`)
);
